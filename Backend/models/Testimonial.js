const mongoose = require('mongoose');

const testimonialSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Client / Colleague Name
    |--------------------------------------------------------------------------
    */

    name: {
      type: String,
      required: [true, 'Name is required'],
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Role / Designation
    |--------------------------------------------------------------------------
    */

    role: {
      type: String,
      default: '',
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Company / Organization
    |--------------------------------------------------------------------------
    */

    company: {
      type: String,
      default: '',
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Testimonial Message
    |--------------------------------------------------------------------------
    */

    message: {
      type: String,
      required: [true, 'Testimonial message is required'],
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Avatar Image
    |--------------------------------------------------------------------------
    */

    avatar: {
      type: String,
      default: '',
    },

    /*
    |--------------------------------------------------------------------------
    | Rating (1-5)
    |--------------------------------------------------------------------------
    */

    rating: {
      type: Number,
      min: 1,
      max: 5,
      default: 5,
    },

    /*
    |--------------------------------------------------------------------------
    | LinkedIn / Profile URL
    |--------------------------------------------------------------------------
    */

    profileUrl: {
      type: String,
      default: '',
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Featured Testimonial
    |--------------------------------------------------------------------------
    */

    featured: {
      type: Boolean,
      default: false,
    },

    /*
    |--------------------------------------------------------------------------
    | Display Order
    |--------------------------------------------------------------------------
    */

    displayOrder: {
      type: Number,
      default: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Visibility
    |--------------------------------------------------------------------------
    */

    isVisible: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('Testimonial', testimonialSchema);