const mongoose = require('mongoose');

const blogPostSchema = new mongoose.Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Title
    |--------------------------------------------------------------------------
    */

    title: {
      type: String,
      required: [true, 'Blog title is required'],
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Slug — URL friendly, unique
    |--------------------------------------------------------------------------
    |
    | Auto-generated from title in the controller. Used for /blog/:slug.
    |
    */

    slug: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      lowercase: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Short Excerpt / Summary
    |--------------------------------------------------------------------------
    */

    excerpt: {
      type: String,
      default: '',
      trim: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Content — Markdown
    |--------------------------------------------------------------------------
    */

    content: {
      type: String,
      required: [true, 'Blog content is required'],
    },

    /*
    |--------------------------------------------------------------------------
    | Cover Image
    |--------------------------------------------------------------------------
    */

    coverImage: {
      type: String,
      default: '',
    },

    /*
    |--------------------------------------------------------------------------
    | Tags
    |--------------------------------------------------------------------------
    */

    tags: {
      type: [String],
      default: [],
    },

    /*
    |--------------------------------------------------------------------------
    | Estimated Read Time (minutes) — auto-calculated in controller
    |--------------------------------------------------------------------------
    */

    readTime: {
      type: Number,
      default: 1,
    },

    /*
    |--------------------------------------------------------------------------
    | View Counter
    |--------------------------------------------------------------------------
    */

    views: {
      type: Number,
      default: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Published State
    |--------------------------------------------------------------------------
    |
    | Draft posts (isPublished: false) sirf admin ko dikhte hain.
    |
    */

    isPublished: {
      type: Boolean,
      default: false,
    },

    /*
    |--------------------------------------------------------------------------
    | Publish Date
    |--------------------------------------------------------------------------
    */

    publishedAt: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Featured Post
    |--------------------------------------------------------------------------
    */

    featured: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('BlogPost', blogPostSchema);